defmodule Pythelix.Plugin.Registry do
  @moduledoc """
  The central list of published plugins.

  A GitHub repository publishes each version of each plugin as a release, and
  keeps an `index.json` describing them all:

      {
        "plugins": {
          "rooms": {
            "1.2.0": {
              "name": "Rooms",
              "description": "Rooms with titles, descriptions and exits.",
              "pythelix": ">=0.9",
              "depends": {"exits": ">=1.0"},
              "url": "https://github.com/.../rooms-1.2.0.tar.gz",
              "sha256": "...",
              "tree_hash": "..."
            }
          }
        }
      }

  The index is what's trusted: it says what an archive's hash has to be, and it
  comes over TLS. It is generated by the registry's CI, never edited by hand.

  Commands run through `eval` don't start any application, and `:httpc` needs
  nothing but `:inets` and `:ssl`, started here when they're needed.
  """

  @default_url "https://raw.githubusercontent.com/vincent-lg/pythelix-plugins/main/index.json"
  @timeout 60_000

  @type version_entry :: map()
  @type index :: %{binary() => %{binary() => version_entry()}}

  @doc """
  Where the index is.
  """
  @spec index_url() :: binary()
  def index_url, do: Application.get_env(:pythelix, :plugin_index_url, @default_url)

  @doc """
  Download the index.
  """
  @spec fetch_index() :: {:ok, index()} | {:error, binary()}
  def fetch_index do
    with {:ok, body} <- download(index_url()) do
      decode_index(body)
    end
  end

  @doc """
  Read an index from text.
  """
  @spec decode_index(binary()) :: {:ok, index()} | {:error, binary()}
  def decode_index(text) do
    case Jason.decode(text) do
      {:ok, %{"plugins" => plugins}} when is_map(plugins) -> {:ok, plugins}
      _unreadable -> {:error, "The plugin index cannot be read."}
    end
  end

  @doc """
  Write an index as text, sorted so that it changes as little as possible.
  """
  @spec encode_index(index()) :: binary()
  def encode_index(index) do
    plugins =
      index
      |> Enum.sort()
      |> Enum.map(fn {key, versions} ->
        {key, versions |> Enum.sort() |> Jason.OrderedObject.new()}
      end)
      |> Jason.OrderedObject.new()

    [plugins: plugins]
    |> Jason.OrderedObject.new()
    |> Jason.encode!(pretty: true)
    |> Kernel.<>("\n")
  end

  @doc """
  Download a URL, following redirects: a release asset is one.
  """
  @spec download(binary()) :: {:ok, binary()} | {:error, binary()}
  def download(url) do
    {:ok, _} = Application.ensure_all_started(:inets)
    {:ok, _} = Application.ensure_all_started(:ssl)

    request = {String.to_charlist(url), [{~c"user-agent", ~c"pythelix"}]}
    options = [ssl: ssl_options(), autoredirect: true, timeout: @timeout]

    case :httpc.request(:get, request, options, body_format: :binary) do
      {:ok, {{_version, 200, _phrase}, _headers, body}} ->
        {:ok, body}

      {:ok, {{_version, status, _phrase}, _headers, _body}} ->
        {:error, "#{url} answered with the status #{status}."}

      {:error, reason} ->
        {:error, "Cannot reach #{url}: #{inspect(reason)}"}
    end
  end

  defp ssl_options do
    [
      verify: :verify_peer,
      cacerts: :public_key.cacerts_get(),
      depth: 3,
      customize_hostname_check: [
        match_fun: :public_key.pkix_verify_hostname_match_fun(:https)
      ]
    ]
  end
end
